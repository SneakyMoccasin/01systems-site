    def test_corrupt_gzip_isolated_without_using_stale_result(self):
        root = self.clone()
        saved_summary = (root / "result.json").read_bytes()
        raw = (self.directory(root) / "history.json.gz").read_bytes()
        for number, (name, damaged, error_type) in enumerate(corrupt_gzip_cases(raw)):
            with self.subTest(corruption=name):
                # Confirm that the fixture exercises the intended decompressor failure.
                with self.assertRaises(error_type):
                    gzip.decompress(damaged)
                index = number % 6
                history = self.directory(root, index) / "history.json.gz"
                original = history.read_bytes()
                history.write_bytes(damaged)
                try:
                    result = self.assert_unknown(root, index)
                    self.assertEqual(result["search_coverage"]["status"], "INCOMPLETE")
                    self.assertEqual(result["search_coverage"]["uncertified"],
                                     [self.manifest["members"][index]["candidate_id"]])
                    self.assertEqual(result["candidates"][index]["run_status"], "UNVERIFIED")
                    self.assertIn("Invalid gzip artifact", result["candidates"][index]["reason"])
                    for other in range(6):
                        if other != index:
                            self.assertEqual(result["candidates"][other], self.result["candidates"][other])
                    # A stale COMPLETE remains on disk, but cannot replace fresh verification.
                    self.assertEqual((root / "result.json").read_bytes(), saved_summary)
                    self.assertEqual(read_bundle(root / "result.json")["search_coverage"]["status"], "COMPLETE")
                    self.assertNotEqual(result["result_id"], self.result["result_id"])
                finally:
                    history.write_bytes(original)

    def test_corrupt_gzip_during_run_does_not_stop_other_candidates(self):
        cli_process = runner.cli_process
        for corruption in ("truncated_trailer", "invalid_header", "invalid_deflate"):
            with self.subTest(corruption=corruption):
                corrupted = []
                def corrupt_after_audit(command, *args):
                    result = cli_process(command, *args)
                    if command == "audit" and not corrupted:
                        history = Path(args[args.index("--history") + 1])
                        damaged = next(raw for name, raw, _ in corrupt_gzip_cases(history.read_bytes())
                                       if name == corruption)
                        history.write_bytes(damaged)
                        corrupted.append(history)
                    return result
                with patch.object(runner, "cli_process", side_effect=corrupt_after_audit):
                    result = self.execute(self.problem, corruption)
                self.assertEqual(len(corrupted), 1)
                self.assertEqual(result["search_coverage"]["status"], "INCOMPLETE")
                first = result["candidates"][0]
                self.assertEqual(first["run_status"], "UNVERIFIED")
                self.assertEqual(first["goal_status"], "UNKNOWN")
                self.assertIsNone(first["goal_satisfied"])
                failure = read_bundle(corrupted[0].with_name("failure.json"))
                self.assertIn("Invalid gzip artifact", failure["reason"])
                for actual, expected in zip(result["candidates"][1:], self.result["candidates"][1:]):
                    for key in ("order", "run_status", "goal_status", "goal_satisfied"):
                        self.assertEqual(actual[key], expected[key])

    def test_artifact_boundary_does_not_swallow_programming_errors(self):
        for error in (RuntimeError("unexpected bug"), AssertionError("broken invariant")):
            with self.subTest(error=type(error).__name__):
                with patch("bridge._read_bundle", side_effect=error):
                    with self.assertRaises(type(error)) as raised:
                        runner.verify(self.complete, self.pins)
                self.assertIs(raised.exception, error)


