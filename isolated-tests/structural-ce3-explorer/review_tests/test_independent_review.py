import runner

ORDERS = {("P", "Q", "X"), ("P", "X", "Q"), ("Q", "P", "X"),
          ("Q", "X", "P"), ("X", "P", "Q"), ("X", "Q", "P")}


def corrupt_gzip_cases(raw):
    return [
        ("truncated_trailer", raw[:-8], EOFError),
        ("truncated_header", raw[:5], EOFError),
        ("truncated_payload", raw[:len(raw) // 2], EOFError),
        ("invalid_header", b"not a gzip stream", gzip.BadGzipFile),
        ("crc_mismatch", raw[:-8] + bytes([raw[-8] ^ 1]) + raw[-7:], gzip.BadGzipFile),
        ("size_mismatch", raw[:-4] + bytes([raw[-4] ^ 1]) + raw[-3:], gzip.BadGzipFile),
        # Standard 10-byte gzip header, then a reserved DEFLATE block type.
        ("invalid_deflate", raw[:10] + b"\x07" + raw[-8:], zlib.error),
        ("truncated_second_member", raw + raw[:5], EOFError),
    ]


class IndependentReview(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory(prefix="ce3-independent-tests-")
        cls.problem = read_bundle(ROOT / "fixtures/problem.json")
        cls.manifest = read_bundle(ROOT / "fixtures/search-manifest.json")
        cls.pins = read_bundle(ROOT / "fixtures/pins.json")
        cls.complete = Path(cls.temp.name) / "baseline"
        cls.result = runner.run(cls.problem, cls.manifest, cls.pins, cls.complete)

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def setUp(self):
        self.work = Path(self.temp.name) / self.id().split(".")[-1]

    def clone(self):
        shutil.copytree(self.complete, self.work)
        return self.work

    def directory(self, root, index=0):
        return root / "runs" / self.manifest["members"][index]["candidate_id"]

    def execute(self, problem, suffix="run", **kwargs):
        manifest, pins = freeze(problem)
        return runner.run(problem, manifest, pins, self.work / suffix, **kwargs)

    def assert_goals(self, result, expected, orders=ORDERS):
        self.assertEqual(result["search_coverage"]["status"], "COMPLETE")
        self.assertEqual({tuple(c["order"]) for c in result["candidates"]}, orders)
        self.assertEqual(len(result["candidates"]), len(orders))
        self.assertTrue(all(c["run_status"] == "CERTIFIED" for c in result["candidates"]))
        self.assertEqual({tuple(c["order"]) for c in result["candidates"]
                          if c["goal_satisfied"] is True}, expected)

    def assert_unknown(self, root, index=0):
        result = runner.verify(root, self.pins)
        self.assertNotEqual(result["search_coverage"]["status"], "COMPLETE")
        self.assertEqual(result["candidates"][index]["goal_status"], "UNKNOWN")
        self.assertIsNone(result["candidates"][index]["goal_satisfied"])
        return result

    def test_independent_literal_scripts_and_baseline(self):
        self.assert_goals(self.result, {("P", "Q", "X"), ("P", "X", "Q"), ("X", "P", "Q")})
        for member in self.manifest["members"]:
            actual = read_bundle(self.complete / "runs" / member["candidate_id"] / "input.json")
            # Direct expected step mapping; never call materialize/member/generate.
            a, b, c = member["order"]
            self.assertEqual(actual["script"]["steps"], {
                "0": [{"decision": a, "mode": "attempt"}],
                "1": [{"decision": b, "mode": "attempt"}],
                "2": [{"decision": c, "mode": "attempt"}]})

    def test_renamed_ids_and_reordered_model_objects(self):
        problem = deepcopy(self.problem)
        names = {"P": "z_start", "Q": "a_finish", "X": "m_aux"}
        problem["model"]["decisions"] = {
            names[k]: v for k, v in reversed(list(problem["model"]["decisions"].items()))}
        problem["search"]["decision_ids"] = ["a_finish", "m_aux", "z_start"]
        result = self.execute(problem)
        orders = {("z_start", "a_finish", "m_aux"), ("z_start", "m_aux", "a_finish"),
                  ("a_finish", "z_start", "m_aux"), ("a_finish", "m_aux", "z_start"),
                  ("m_aux", "z_start", "a_finish"), ("m_aux", "a_finish", "z_start")}
        self.assert_goals(result, {("z_start", "a_finish", "m_aux"),
                                  ("z_start", "m_aux", "a_finish"),
                                  ("m_aux", "z_start", "a_finish")}, orders)
        reordered = deepcopy(self.problem)
        reordered["model"]["decisions"] = dict(reversed(list(reordered["model"]["decisions"].items())))
        self.assertEqual(digest(reordered), self.pins["problem_id"])
        self.assertEqual(freeze(reordered), (self.manifest, self.pins))
        reordered["search"]["decision_ids"] = ["X", "Q", "P"]
        with self.assertRaisesRegex(ValueError, "canonical"):
            validate_problem(reordered)

    def test_reversed_guard_changes_winning_orders(self):
        problem = deepcopy(self.problem)
        problem["model"]["decisions"]["Q"]["requires"][0]["value"] = False
        self.assert_goals(self.execute(problem), {("Q", "P", "X"), ("Q", "X", "P"), ("X", "Q", "P")})

    def test_conjunctive_guard_and_delay_boundary(self):
        problem = deepcopy(self.problem)
        problem["model"]["decisions"]["Q"]["requires"].append({"field": "aux_done", "op": "eq", "value": True})
        self.assert_goals(self.execute(problem, "conjunction"), {("P", "X", "Q"), ("X", "P", "Q")})
        problem = deepcopy(self.problem)
        problem["model"]["decisions"]["P"]["schedule"]["delay"] = 2
        self.assert_goals(self.execute(problem, "delay_two"), {("P", "X", "Q")})
        problem["model"]["decisions"]["P"]["schedule"]["delay"] = 3
        self.assert_goals(self.execute(problem, "after_horizon"), set())

    def test_integer_string_goals_no_budget_no_events(self):
        problem = deepcopy(self.problem)
        model = problem["model"]
        model.update(domains={"n": {"integer": [0, 1]}, "phase": {"enum": ["idle", "started", "done"]}},
                     initial={"n": 0, "phase": "idle"}, budget=None, events={},
                     initial_events=[], reference_event_order=[])
        def rule(requires, sets, adds):
            return {"requires": requires, "effects": {"set": sets, "add": adds},
                    "cost": 0, "schedule": None, "source": "Independent review fixture"}
        model["decisions"] = {
            "A": rule([], {"phase": "started"}, {"n": 1}),
            "B": rule([{"field": "phase", "op": "eq", "value": "started"}], {"phase": "done"}, {}),
            "C": rule([{"field": "n", "op": "ge", "value": 1}], {}, {})}
        problem["search"]["decision_ids"] = ["A", "B", "C"]
        problem["observation"]["terminal_equals"] = {"n": 1, "phase": "done"}
        orders = {("A", "B", "C"), ("A", "C", "B"), ("B", "A", "C"),
                  ("B", "C", "A"), ("C", "A", "B"), ("C", "B", "A")}
        self.assert_goals(self.execute(problem), {("A", "B", "C"), ("A", "C", "B")}, orders)

    def test_goal_types_and_scope_rejections(self):
        for goal in ({}, {"budget": True}, {"done": 1}, {"budget": 3},
                     {"budget": -1}, {"budget": 1.0}, {"unknown": True}, {"done": None}):
            with self.subTest(goal=goal):
                problem = deepcopy(self.problem)
                problem["observation"]["terminal_equals"] = goal
                with self.assertRaises(ValueError):
                    validate_problem(problem)
        for ids in (["P", "Q"], ["P", "Q", "X", "Y"]):
            problem = deepcopy(self.problem)
            problem["search"]["decision_ids"] = ids
            with self.assertRaisesRegex(ValueError, "Exactly three"):
                validate_problem(problem)
        for field, value in (("sampling", "initial"), ("quantifier", "any_event_path"),
                             ("all_attempts_accepted", False)):
            problem = deepcopy(self.problem)
            problem["observation"][field] = value
            with self.assertRaises(ValueError):
                validate_problem(problem)

    def test_true_terminal_goal_does_not_hide_blocked_attempt(self):
        problem = deepcopy(self.problem)
        problem["observation"]["terminal_equals"] = {"prepared": True}
        self.assert_goals(self.execute(problem), {("P", "Q", "X"), ("P", "X", "Q"), ("X", "P", "Q")})
        problem["observation"]["terminal_equals"] = {"budget": 1}
        # Only blocked runs end at 1; conjunction with all accepted is false for all.
        self.assert_goals(self.execute(problem, "budget_one"), set())

    def test_consistent_omission_manifest_enumeration_results_and_pins(self):
        root = self.clone()
        bad = deepcopy(self.manifest)
        omitted = bad["members"].pop(4)  # XPQ, independently known member.
        pins = dict(self.pins, manifest_id=digest(bad))
        write_bundle(bad, root / "manifest.json")
        write_bundle(bad["members"], root / "enumeration.json")
        write_bundle(pins, root / "pins.json")
        shutil.rmtree(root / "runs" / omitted["candidate_id"])
        spec = read_bundle(root / "search.json")
        spec["manifest_id"] = digest(bad)
        write_bundle(spec, root / "search.json")
        for member in bad["members"]:
            directory = root / "runs" / member["candidate_id"]
            for name in ("started.json", "record.json"):
                record = read_bundle(directory / name)
                record.update(manifest_id=digest(bad), search_execution_id=digest(spec))
                write_bundle(record, directory / name)
        summary = deepcopy(self.result)
        summary["candidates"] = [c for c in summary["candidates"] if c["candidate_id"] != omitted["candidate_id"]]
        summary.update(manifest_id=digest(bad), search_execution_id=digest(spec))
        summary["enumeration_coverage"] = check_coverage(bad, bad["members"])
        del summary["result_id"]
        summary["result_id"] = digest(summary)
        write_bundle(summary, root / "result.json")
        # Membership-only checking is COMPLETE; full problem checking must reject.
        self.assertEqual(summary["enumeration_coverage"]["status"], "COMPLETE")
        with self.assertRaisesRegex(ValueError, "identity mismatch"):
            runner.verify(root, pins)

    def test_old_runs_rejected_under_new_goal_and_revision_even_with_new_pins(self):
        root = self.clone()
        problem = deepcopy(self.problem)
        problem["revision"] = 2
        problem["observation"]["terminal_equals"] = {"done": False}
        manifest, pins = freeze(problem)
        for name, value in (("problem.json", problem), ("manifest.json", manifest), ("pins.json", pins)):
            write_bundle(value, root / name)
        spec = read_bundle(root / "search.json")
        spec.update(problem_id=digest(problem), manifest_id=digest(manifest))
        write_bundle(spec, root / "search.json")
        result = runner.verify(root, pins)
        self.assertEqual(result["search_coverage"]["status"], "INCOMPLETE")
        self.assertTrue(all(c["goal_satisfied"] is None for c in result["candidates"]))

    def test_individual_artifact_swaps_and_forged_observation_evidence(self):
        root = self.clone()
        target, source = self.directory(root), self.directory(root, 1)
        for name in ("input.json", "history.json.gz", "audit.json", "audit-receipt.json",
                     "observation.json", "started.json", "record.json"):
            with self.subTest(name=name):
                original = (target / name).read_bytes()
                shutil.copyfile(source / name, target / name)
                self.assert_unknown(root)
                (target / name).write_bytes(original)
        for field in ("terminal_evidence", "attempt_evidence", "terminal_checks", "terminal_state", "event_orders"):
            with self.subTest(field=field):
                observation = read_bundle(target / "observation.json")
                observation["paths"][0][field] = []
                write_bundle(observation, target / "observation.json")
                record = read_bundle(target / "record.json")
                record["observation_id"] = digest(observation)
                write_bundle(record, target / "record.json")
                self.assert_unknown(root)
                for name in ("record.json", "observation.json"):
                    shutil.copyfile(self.directory(self.complete) / name, target / name)

    def test_missing_runs_duplicate_uuid_and_broken_json(self):
        root = self.clone()
        first, second = self.directory(root), self.directory(root, 1)
        first_id = read_bundle(first / "record.json")["run_id"]
        for name in ("record.json", "started.json"):
            obj = read_bundle(second / name)
            obj["run_id"] = first_id
            write_bundle(obj, second / name)
        self.assert_unknown(root, 1)
        shutil.rmtree(first)
        result = self.assert_unknown(root)
        self.assertEqual(result["candidates"][0]["run_status"], "NOT_RUN")
        for name in ("record.json", "started.json"):
            shutil.copyfile(self.directory(self.complete, 1) / name, second / name)
        for raw in (b'{', b'{"status": "PASS", "status": "FAIL"}', b'null'):
            (second / "audit.json").write_bytes(raw)
            self.assert_unknown(root, 1)

